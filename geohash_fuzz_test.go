package geohash

import (
	"math"
	"testing"
)

// FuzzEncodeDecode verifies the "Round Trip" property and input validation.
// Property: Encode(lat, lon) -> hash -> Decode(hash) -> (lat2, lon2) -> Encode(lat2, lon2) == hash.
func FuzzEncodeDecode(f *testing.F) {
	// Seed Corpus
	f.Add(37.7749, -122.4194, int(12)) // San Francisco
	f.Add(0.0, 0.0, int(1))            // Null Island
	f.Add(90.0, 180.0, int(6))         // Max Boundaries
	f.Add(-90.0, -180.0, int(6))       // Min Boundaries

	f.Fuzz(func(t *testing.T, lat float64, lon float64, precInt int) {
		prec := Precision(precInt)

		// Determine validity using a closure to enable readable "Early Return" pattern.
		isValidInput := func() bool {
			// Check Latitude
			if math.IsNaN(lat) || math.IsInf(lat, 0) {
				return false
			}
			if lat < minLatitude || lat > maxLatitude {
				return false
			}

			// Check Longitude
			if math.IsNaN(lon) || math.IsInf(lon, 0) {
				return false
			}
			if lon < minLongitude || lon > maxLongitude {
				return false
			}

			// Check Precision
			if prec < Global || prec > SubPoint {
				return false
			}

			return true
		}()

		hash, err := Encode(lat, lon, prec)

		// Check 1: Verify Encode correctly accepts/rejects inputs
		if err != nil {
			if isValidInput {
				t.Fatalf("Encode failed on valid input: lat=%f, lon=%f, p=%d, err=%v", lat, lon, prec, err)
			}
			// Expected error on invalid input, stop iteration
			return
		}

		if !isValidInput {
			t.Fatalf("Encode succeeded on invalid input: lat=%f, lon=%f, p=%d, hash=%s", lat, lon, prec, hash)
		}

		// Check 2: Verify decoding the generated hash works
		decodedLat, decodedLon, err := Decode(hash)
		if err != nil {
			t.Fatalf("Failed to Decode a hash generated by Encode: %s, err=%v", hash, err)
		}

		// Check 3: Verify Round Trip (Re-Encoding must match original hash)
		reHash, err := Encode(decodedLat, decodedLon, prec)
		if err != nil {
			t.Fatalf("Re-Encode failed for lat=%f, lon=%f: %v", decodedLat, decodedLon, err)
		}

		if hash != reHash {
			t.Errorf("Round Trip failed.\nOriginal: %s (Lat: %f, Lon: %f)\nRe-Encoded: %s (Lat: %f, Lon: %f)",
				hash, lat, lon, reHash, decodedLat, decodedLon)
		}
	})
}

// FuzzDecodeRobustness ensures Decode never panics on random input strings.
func FuzzDecodeRobustness(f *testing.F) {
	f.Add("u4pruydqqvj")
	f.Add("zzzzz")
	f.Add("0")
	f.Add("!!!!!!") // Invalid chars

	f.Fuzz(func(t *testing.T, hash string) {
		// We ignore return values and errors; we only care that it does not panic.
		_, _, _ = Decode(hash)
		_, _, _, _ = DecodeBBox(hash)
	})
}

// FuzzNeighborsRobustness ensures finding neighbors never panics, even with edge cases.
func FuzzNeighborsRobustness(f *testing.F) {
	f.Add("u4pruydqqvj")
	f.Add("zzzzz") // North Pole extreme
	f.Add("00000") // South Pole extreme

	f.Fuzz(func(t *testing.T, hash string) {
		neighbors, err := Neighbors(hash)

		if err != nil {
			// Invalid hash inputs should return an error, not panic.
			return
		}

		// If success, we enforce structural integrity of the result.
		if len(neighbors) != 8 {
			t.Errorf("Expected 8 neighbors for hash %s, got %d", hash, len(neighbors))
		}

		for _, n := range neighbors {
			if len(n) != len(hash) {
				t.Errorf("Neighbor %s has different precision than original %s", n, hash)
			}

			// Ensure neighbor itself is a valid geohash
			if _, _, err := Decode(n); err != nil {
				t.Errorf("Neighbor %s produced invalid hash from parent %s", n, hash)
			}
		}
	})
}
